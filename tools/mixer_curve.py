"""Print the analog mixer's distortion table and constants as C.

The Model D mixer sums the sources through 33 kOhm resistors into the filter's input transistor
pair, whose output follows tanh(v / 2 VT). In engine units s (a saw peaks at 0.948) the mixer
gives tanh(DRIVE * s) / DRIVE, unity for small signals; DRIVE is a model choice inside the range
the drawings allow (see docs/analog.md). The table holds the distortion alone,
(tanh(a) - a) / DRIVE at a = DRIVE * s, in output Q31 and divided by 6 for Simpson's rule."""
import numpy as np

DRIVE, STEPS, SPAN = 0.6, 512, 8.0
UNIT = 2**31 / 16   # Q31 per engine unit

if __name__ == "__main__":
    k = round(DRIVE / UNIT * 2**12 * 2**24)   # (|q| >> 12) * k = a in Q24
    drive = k * UNIT / 2**36                  # the drive the rounded constant gives
    a = np.arange(STEPS + 1) * SPAN / STEPS
    table = np.round((np.tanh(a) - a) / drive * UNIT / 6).astype(np.int64)
    print(f"/* Generated by tools/mixer_curve.py: drive {drive:.6f} per engine unit (nominal {DRIVE}), a = drive * s over 0..{SPAN:g} in {STEPS} steps. */")
    print(f"#define MIX_DRIVE {k}   /* (|q| >> 12) * this = a, Q24 */")
    print(f"static const int32_t mix_distortion[{STEPS + 1}] = {{   /* (tanh(a) - a) / drive / 6, output Q31 */")
    for i in range(0, STEPS + 1, 8):
        print("    " + ", ".join(str(int(x)) for x in table[i:i + 8]) + ",")
    print("};")
