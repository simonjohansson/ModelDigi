"""Print the engine's edge-correction tables as C.

The kernel is a Kaiser-windowed sinc, unit area, reaching HALF samples either side: a step
or a slope change smoothed by it is the ideal waveform low-passed by the kernel's response.
For an event d samples (0 <= d <= 1) before sample n, row d holds the residues at samples
n - HALF through n + HALF - 1: the step's (smoothed minus ideal step) and the slope change's
(its integral)."""
import numpy as np

HALF, BETA, CUTOFF, FS, PHASES = 6, 5.5, 20500.0, 48000.0, 64


def kernel(u):
    w = np.i0(BETA * np.sqrt(np.clip(1 - (u / HALF) ** 2, 0, None))) / np.i0(BETA)
    return 2 * CUTOFF / FS * np.sinc(2 * CUTOFF / FS * u) * w * (abs(u) <= HALF)


def residues():
    u = np.linspace(-HALF, HALF, 2 * HALF * 8192 + 1)
    k = kernel(u)
    step = np.concatenate([[0], np.cumsum((k[1:] + k[:-1]) / 2 * np.diff(u))])
    step /= step[-1]
    r = step - (u >= 0)
    ramp = np.concatenate([[0], np.cumsum((r[1:] + r[:-1]) / 2 * np.diff(u))])
    return u, r, ramp


def tables():
    u, r, ramp = residues()
    zero = np.searchsorted(u, 0)

    def pick(curve, x, last_row):
        # The step residue jumps at the event. A sample at the event counts as after it, except in
        # the last row, which only ends the interpolation towards d = 1: there the sample is just
        # before the event.
        if x == 0:
            return curve[zero - 1] if last_row else curve[zero]
        return np.interp(x, u, curve)
    rows = [[j - HALF + p / PHASES for j in range(2 * HALF)] for p in range(PHASES + 1)]
    return ([[pick(r, x, p == PHASES) for x in row] for p, row in enumerate(rows)],
            [[pick(ramp, x, p == PHASES) for x in row] for p, row in enumerate(rows)])


if __name__ == "__main__":
    step, bend = tables()
    print(f"#define EDGE_HALF {HALF}")
    print(f"/* Generated by tools/edge_kernel.py: Kaiser-windowed sinc, beta {BETA}, cutoff {CUTOFF:.0f} Hz, {HALF} samples")
    print(f" * either side. Row p: an event p / {PHASES} of a sample before sample n; entries for samples")
    print(f" * n - {HALF} through n + {HALF - 1}. Steps Q15, slope changes Q17. */")
    for name, table, scale in (("step", step, 32768), ("bend", bend, 131072)):
        values = np.round(np.array(table) * scale).astype(int)
        delta = values[1:] - values[:-1]
        assert abs(values).max() < 32768 and abs(delta).max() < 32768
        print(f"/* Rows 0..{PHASES - 1}: each residue in the high half, its step to the next row in the low half. */")
        print(f"static const int32_t {name}_pairs[{PHASES}][{2 * HALF}] = {{")
        for row, step_row in zip(values[:-1], delta):
            print("    { " + ", ".join(f"{(int(a) << 16) | (int(d) & 0xffff):#010x}" for a, d in zip(row, step_row)) + " },")
        print("};")
        print(f"/* Row sums of the residues and of their steps. */")
        print(f"static const int32_t {name}_sums[{PHASES}][2] = {{")
        for a, d in zip(values[:-1].sum(axis=1), delta.sum(axis=1)):
            print(f"    {{ {a}, {d} }},")
        print("};")
    u, r, ramp = residues()
    offset = np.trapezoid(ramp, u)
    print(f"/* A slope change's residues over every sample sum to (d^2 - d + 1/6) / 2 plus the residue's")
    print(f" * integral, {offset:.7f}; Q17. */")
    print(f"#define BEND_SUM_OFFSET {round(offset * 131072)}")
